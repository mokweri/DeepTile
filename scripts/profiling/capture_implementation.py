#!/usr/bin/env python3
"""Preserve routed implementation evidence, including the kernel's real clock."""

import argparse
import hashlib
import json
import re
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path


def digest(path):
    result = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def timing_summary(text):
    if not re.search(r"Design State\s*:\s*(?:Routed|Physopt postRoute)\s*\n", text):
        raise ValueError("Expected routed timing report")
    match = re.search(r"WNS\(ns\).*\n\s*[- ]+\n([^\n]+)", text)
    if not match:
        raise ValueError("Missing whole-design timing table")
    values = match.group(1).split()
    if len(values) != 12:
        raise ValueError("Unexpected timing table columns")
    fields = ("wns_ns", "tns_ns", "setup_failing_endpoints", "setup_endpoints",
              "whs_ns", "ths_ns", "hold_failing_endpoints", "hold_endpoints",
              "wpws_ns", "tpws_ns", "pulse_failing_endpoints", "pulse_endpoints")
    result = {name: (int(value) if "endpoints" in name else float(value))
              for name, value in zip(fields, values)}
    result["constraints_met"] = "All user specified timing constraints are met." in text
    return result


def resources(text, name):
    if not re.search(r"Design State\s*:\s*(?:Routed|Physopt postRoute)\s*\n", text):
        raise ValueError("Expected routed accelerator utilization")
    match = re.search(r"^\|\s*" + re.escape(name) + r"\s*\|(.+)\|$", text, re.M)
    if not match:
        raise ValueError(f"Missing utilization row: {name}")
    values = [float(cell.strip().split()[0]) for cell in match.group(1).split("|")]
    if len(values) != 6:
        raise ValueError("Unexpected utilization columns")
    return dict(zip(("lut", "lut_as_memory", "registers", "bram36", "uram", "dsp"), values))


def bus_skew_summary(text):
    match = re.search(r"\n1\. Bus Skew Report Summary\n-+\n(.*?)\n2\. Bus Skew Report Per Constraint\n",
                      text, re.S)
    if not match:
        raise ValueError("Missing bus-skew summary table")
    table = match.group(1)
    expected = len(re.findall(r"^\d+\s+\d+\s+", table, re.M))
    rows = re.findall(r"^\s*(?:Slow|Fast)\s+(-?[\d.]+)\s+(-?[\d.]+)\s+(-?[\d.]+)\s*$",
                      table, re.M)
    if not expected or len(rows) != expected:
        raise ValueError("Missing or unrecognized bus-skew constraints")
    slack = [float(row[2]) for row in rows]
    return {"constraints": len(rows), "failing_constraints": sum(value < 0 for value in slack),
            "minimum_slack_ns": min(slack)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--checkpoint-reports", type=Path,
                        help="Reports generated by report_final_checkpoint.tcl from the final DCP")
    args = parser.parse_args()
    target = args.target
    report_root = target / "vpp_temp/reports/link/imp"
    files = {
        "timing.rpt": report_root / "impl_1_vitis_design_wrapper_timing_summary_routed.rpt",
        "utilization.rpt": report_root / "impl_1_kernel_util_routed.rpt",
        "design.hwh": target / "vpp_temp/link/vivado/vpl/prj/prj.gen/sources_1/bd/vitis_design/hw_handoff/vitis_design.hwh",
        "target-build.json": target / "target-build.json",
        "target.json": target / "target.json",
    }
    final_timing = report_root / "impl_1_vitis_design_wrapper_timing_summary_postroute_physopted.rpt"
    resource_phase_note = "Accelerator utilization after routing"
    if final_timing.is_file():
        files["timing-before-physical-opt.rpt"] = files["timing.rpt"]
        files["timing.rpt"] = final_timing
        # The generated flow does not rerun utilization after optional physical
        # optimization. Require evidence that it left the routed netlist intact.
        files["implementation.log"] = target / "vpp_temp/link/vivado/vpl/prj/prj.runs/impl_1/runme.log"
        postroute = files["implementation.log"].read_text().rsplit(
            "Starting optional post-route physical design optimization.", 1)[-1]
        postroute = postroute.split("Finished optional post-route physical design optimization.", 1)[0]
        if "The netlist was not modified." not in postroute and not args.checkpoint_reports:
            raise ValueError("Post-route optimization may change utilization; collect it from the final checkpoint")
        resource_phase_note += "; final physical optimization did not modify the netlist (see implementation.log)"
    checkpoint_hash = None
    if args.checkpoint_reports:
        checkpoint = target / "vpp_temp/link/vivado/vpl/prj/prj.runs/impl_1/vitis_design_wrapper_postroute_physopt.dcp"
        checkpoint_hash = digest(checkpoint)
        reports = args.checkpoint_reports
        files["checkpoint.sha256"] = reports / "checkpoint.sha256"
        if files["checkpoint.sha256"].read_text().split()[0] != checkpoint_hash:
            raise ValueError("Final report checkpoint digest differs from this build's final checkpoint")
        files["timing-generated-flow.rpt"] = files["timing.rpt"]
        files["utilization-before-physical-opt.rpt"] = files["utilization.rpt"]
        files["timing.rpt"] = reports / "final-timing.rpt"
        files["utilization.rpt"] = reports / "final-utilization.rpt"
        files["bus-skew.rpt"] = reports / "final-bus-skew.rpt"
        resource_phase_note = "Read directly from the SHA256-bound final post-route physical-optimization checkpoint"
    for path in files.values():
        if not path.is_file():
            raise FileNotFoundError(path)
    record = json.loads(files["target-build.json"].read_text())
    manifest = json.loads(files["target.json"].read_text())
    xclbin_hash = digest(target / manifest["artifact"]["xclbin"])
    if (record["state"] != "complete" or
            record["artifact"]["sha256"] != xclbin_hash or
            manifest["artifact"]["sha256"] != xclbin_hash):
        raise ValueError("Completed build record, manifest and XCLBIN do not agree")
    hwh = ET.parse(files["design.hwh"])
    cu = record["settings"]["compute_unit"]
    ports = hwh.findall(f".//MODULE[@INSTANCE='{cu}']/PORTS/PORT[@NAME='ap_clk']")
    if len(ports) != 1:
        raise ValueError("Expected one kernel ap_clk port in the block-design handoff")
    port = ports[0]
    summary = {
        "schema": "deeptile.architecture-implementation.v1",
        "original_target": str(target),
        "xclbin_sha256": xclbin_hash,
        "settings": record["settings"],
        "kernel_clock": {
            "frequency_hz": int(port.attrib["CLKFREQUENCY"]),
            "signal": port.attrib["SIGNAME"],
            "connections": [node.attrib for node in port.findall("CONNECTIONS/CONNECTION")],
            "source": "kernel ap_clk port in implemented block-design handoff; not requested clock or XCLBIN metadata",
        },
        "timing": timing_summary(files["timing.rpt"].read_text()),
        "timing_report": files["timing.rpt"].name,
        "resource_report": files["utilization.rpt"].name,
        "resource_phase_note": resource_phase_note,
        "final_checkpoint_sha256": checkpoint_hash,
        "bus_skew": bus_skew_summary(files["bus-skew.rpt"].read_text()) if args.checkpoint_reports else None,
        "kernel_resources": resources(files["utilization.rpt"].read_text(), "tile_conv"),
        "platform_resources": resources(files["utilization.rpt"].read_text(), "Platform"),
        "preserved_sha256": {name: digest(path) for name, path in files.items()},
    }
    args.output.mkdir(parents=True, exist_ok=False)
    for name, path in files.items():
        shutil.copy2(path, args.output / name)
    (args.output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({key: summary[key] for key in
                      ("kernel_clock", "timing", "kernel_resources", "platform_resources")}, indent=2))


if __name__ == "__main__":
    main()
